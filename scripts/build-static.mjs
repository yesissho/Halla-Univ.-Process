import {readFileSync,writeFileSync,mkdirSync,rmSync,copyFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
import {fileURLToPath} from 'node:url';
import path from 'node:path';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const read=n=>readFileSync(path.join(root,'src',n),'utf8');
const hash=s=>createHash('sha256').update(s).digest('hex').slice(0,12);
const app=read('app.js'),style=read('style.css');
const appName=`app-${hash(app)}.js`,styleName=`style-${hash(style)}.css`;
const dist=path.join(root,'dist');rmSync(dist,{recursive:true,force:true});mkdirSync(dist,{recursive:true});
writeFileSync(path.join(dist,appName),app);writeFileSync(path.join(dist,'app.js'),app);writeFileSync(path.join(dist,styleName),style);
writeFileSync(path.join(dist,'index.html'),read('index.html').replaceAll('{{APP_FILE}}',appName).replaceAll('{{STYLE_FILE}}',styleName));
copyFileSync(path.join(root,'src/campus.svg'),path.join(dist,'campus.svg'));
console.log(`Built dist/index.html, ${appName}, ${styleName}, app.js, campus.svg`);
